#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const [input, commit] = process.argv.slice(2)

if (!input || !/^[0-9a-f]{40}$/.test(commit ?? '')) {
  console.error('usage: generate-browser-public-suffix-asset.mjs <public_suffix_list.dat> <40-char-commit>')
  process.exit(2)
}

const source = readFileSync(resolve(input), 'utf8')
const rules = source
  .split(/\r?\n/u)
  .map(line => line.trim())
  .filter(line => line && !line.startsWith('//'))
const canonical = rules.join('\n')
const checksum = createHash('sha256').update(canonical).digest('hex')
const version = `publicsuffix-list-${commit.slice(0, 12)}`
const output = `// Generated by scripts/generate-browser-public-suffix-asset.mjs.\n` +
  `// Source: https://github.com/publicsuffix/list/blob/${commit}/public_suffix_list.dat\n` +
  `// License: Mozilla Public License 2.0. Do not edit this snapshot by hand.\n` +
  `export const BUNDLED_PSL_VERSION = ${JSON.stringify(version)}\n` +
  `export const BUNDLED_PSL_SOURCE_COMMIT = ${JSON.stringify(commit)}\n` +
  `export const BUNDLED_PSL_RULES_SHA256 = ${JSON.stringify(checksum)}\n` +
  `export const BUNDLED_PSL_RULES = ${JSON.stringify(canonical)}\n`

writeFileSync(new URL('../electron/browser-public-suffix-asset.ts', import.meta.url), output)
console.log(JSON.stringify({ checksum, rules: rules.length, version }))
